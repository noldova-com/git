import assert from "node:assert/strict";

import { FailureCode } from "@noldova/desktop.protocol";
import { MethodFailureException } from "@noldova/desktop.runtime";
import { FakeModuleLog } from "@noldova/desktop.runtime/testing";
import { AuthorQuery, PersonQuery } from "@noldova/git.hosting.protocol";
import { describe, it } from "vitest";

import { AzureApi } from "../../src/services/azure-api.ts";
import { AzureAvatars } from "../../src/services/azure-avatars.ts";
import { FakeAzure, FakeToken, linesOf } from "../fixtures/fake-azure.fixture.ts";

const signal: AbortSignal = new AbortController().signal;
const commit: string = "6dcb09b5b57875f334f61aebed695e2e4193db5e";
const queryUrl: string = "https://vssps.dev.azure.com/fabrikam/_apis/graph/subjectquery?api-version=7.1-preview.1";
const avatarUrl: string = "https://vssps.dev.azure.com/fabrikam/_apis/graph/Subjects/aad.TW9uYQ%3D%3D/avatars?size=medium&api-version=7.1-preview.1";
const png: Buffer = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

function users(...mails: readonly (string | null)[]): Response {
  return FakeAzure.json({ count: mails.length, value: mails.map((t, i) => ({ subjectKind: "user", mailAddress: t, descriptor: i === mails.length - 1 ? "aad.TW9uYQ==" : `aad.${i}` })) });
}

function picture(bytes: Buffer, isAutoGenerated: boolean = false): Response {
  return FakeAzure.json({ isAutoGenerated, size: "medium", timeStamp: "2027-01-15T09:30:00Z", value: bytes.toString("base64") });
}

function query(email: string = "monalisa@fabrikam.com", organization: string = "fabrikam", host: string = "dev.azure.com"): AuthorQuery {
  return new AuthorQuery(host, organization, email, commit);
}

class Rig {
  public readonly azure: FakeAzure = new FakeAzure();
  public readonly token: FakeToken;
  public readonly log: FakeModuleLog = new FakeModuleLog();
  public readonly avatars: AzureAvatars;

  public constructor(token: FakeToken = new FakeToken()) {
    this.token = token;
    this.avatars = new AzureAvatars(new AzureApi(this.azure.fetch), this.token, this.log);
  }

  public readAsync(author: AuthorQuery = query()): Promise<string | null> {
    return this.avatars.readAuthorAvatarAsync(author, signal);
  }

  public readPersonAsync(login: string, organization: string = "fabrikam", host: string = "dev.azure.com"): Promise<string | null> {
    return this.avatars.readPersonAvatarAsync(new PersonQuery(host, organization, login), signal);
  }
}

describe("AzureAvatars", () => {
  it("finds a person by their sign-in email as it finds an author, sharing the answers it keeps with the authors' by organization and email", async () => {
    const rig = new Rig();
    rig.azure.answer(users("monalisa@fabrikam.com"), picture(png));

    const avatars = [await rig.readPersonAsync(" MonaLisa@Fabrikam.com "), await rig.readAsync(query("monalisa@fabrikam.com", "Fabrikam"))];

    assert.deepEqual([avatars, rig.azure.urls(), JSON.parse(String(rig.azure.requests[0]?.init.body))],
      [[`data:image/png;base64,${png.toString("base64")}`, `data:image/png;base64,${png.toString("base64")}`], [queryUrl, avatarUrl],
        { query: "monalisa@fabrikam.com", subjectKind: ["User"] }]);
  });

  it("answers none and asks nothing for a person whose sign-in name isn't an email, another host or organization, or signed out", async () => {
    const rig = new Rig();
    const signedOut = new Rig(new FakeToken(null));

    const avatars = [await rig.readPersonAsync("FABRIKAM\\mona"), await rig.readPersonAsync("mona lisa@fabrikam.com"), await rig.readPersonAsync("@fabrikam.com"),
      await rig.readPersonAsync("monalisa@fabrikam.com", "fabrikam", "github.com"), await rig.readPersonAsync("monalisa@fabrikam.com", "contoso"),
      await signedOut.readPersonAsync("monalisa@fabrikam.com")];

    assert.deepEqual([avatars, rig.azure.requests.length, signedOut.azure.requests.length], [[null, null, null, null, null, null], 0, 0]);
  });

  it("finds the organization's user by the author's email through Graph and answers their picture as a data address, asking once per email", async () => {
    const rig = new Rig();
    rig.azure.answer(users(null, "octocat@fabrikam.com", "MonaLisa@Fabrikam.com"), picture(png));

    const avatars = [await rig.readAsync(query(" MonaLisa@fabrikam.com ")), await rig.readAsync(query("monalisa@fabrikam.com", "Fabrikam"))];

    assert.deepEqual(avatars, [`data:image/png;base64,${png.toString("base64")}`, `data:image/png;base64,${png.toString("base64")}`]);
    assert.deepEqual([rig.azure.urls(), rig.azure.requests[0]?.init.method, rig.azure.requests[0]?.header("Content-Type"),
      JSON.parse(String(rig.azure.requests[0]?.init.body)), rig.azure.requests.map(t => t.header("Authorization"))],
      [[queryUrl, avatarUrl], "POST", "application/json", { query: "monalisa@fabrikam.com", subjectKind: ["User"] },
        [rig.token.token?.authorization, rig.token.token?.authorization]]);
  });

  it("answers none and asks nothing for another host or organization, or signed out", async () => {
    const rig = new Rig();
    const signedOut = new Rig(new FakeToken(null));

    const avatars = [await rig.readAsync(query(undefined, "fabrikam", "github.com")), await rig.readAsync(query(undefined, "contoso")),
      await signedOut.readAsync()];

    assert.deepEqual([avatars, rig.azure.requests.length, signedOut.azure.requests.length], [[null, null, null], 0, 0]);
  });

  it("answers none, once, for an email no user has, an organization or picture Azure DevOps doesn't find, and a picture Azure DevOps made itself", async () => {
    const rig = new Rig();
    rig.azure.answer(users("octocat@fabrikam.com"), new Response(null, { status: 404 }), users("monalisa@fabrikam.com"), new Response(null, { status: 404 }),
      users("hubot@fabrikam.com"), picture(png, true));

    const avatars = [await rig.readAsync(query("monalisa@contoso.com")), await rig.readAsync(query("octocat@contoso.com")),
      await rig.readAsync(), await rig.readAsync(query("hubot@fabrikam.com")), await rig.readAsync(query("monalisa@contoso.com"))];

    assert.deepEqual([avatars, rig.azure.requests.length], [[null, null, null, null, null], 6]);
  });

  it("answers a JPEG, GIF or WebP picture with its type, and logs a picture that is empty, over 64 KiB or no image it knows, showing none", async () => {
    const rig = new Rig();
    const pictures: readonly Buffer[] = [Buffer.from([0xff, 0xd8, 0xff, 0xe0]), Buffer.from("GIF89a"), Buffer.from("RIFF\u0000\u0000\u0000\u0000WEBPVP8 "),
      Buffer.alloc(0), Buffer.alloc(65_537, 0x89), Buffer.from("RIFF\u0000\u0000\u0000\u0000WAVE")];
    const emails: readonly string[] = pictures.map((_t, i) => `author${i}@fabrikam.com`);
    for (const [i, bytes] of pictures.entries())
      rig.azure.answer(users(emails[i] ?? null), picture(bytes));

    const avatars: (string | null)[] = [];
    for (const email of emails)
      avatars.push(await rig.readAsync(query(email)));

    assert.deepEqual(avatars.map(t => t?.slice(0, t.indexOf(";")) ?? null), ["data:image/jpeg", "data:image/gif", "data:image/webp", null, null, null]);
    assert.deepEqual(linesOf(rig.log), ["An Azure DevOps picture isn't shown: the image is empty.", "An Azure DevOps picture isn't shown: the image is over 64 KiB.",
      "An Azure DevOps picture isn't shown: the answer isn't a PNG, JPEG, GIF or WebP image."]);
  });

  it("tells the sign-in when Azure DevOps refuses the token and passes the failure on, as it does an unreadable answer, keeping neither", async () => {
    const rig = new Rig();
    rig.azure.answer(new Response(null, { status: 401 }), FakeAzure.json({ value: [{ mailAddress: "monalisa@fabrikam.com" }] }), users("monalisa@fabrikam.com"),
      picture(png));

    const failures = [await rig.readAsync().then(() => null, (t: unknown) => t), await rig.readAsync().then(() => null, (t: unknown) => t)];
    const avatar: string | null = await rig.readAsync();

    assert.deepEqual(failures.map(t => t instanceof MethodFailureException ? t.failure.code : t), [FailureCode.Unauthorized, FailureCode.Unavailable]);
    assert.deepEqual([rig.token.refused, avatar?.startsWith("data:image/png;base64,")], [["azure-token"], true]);
  });

  it("answers none and keeps nothing when the sign-in changed during the read", async () => {
    const rig = new Rig();
    const release = rig.azure.hold();
    rig.azure.answer(users("monalisa@fabrikam.com"), picture(png));

    const reading: Promise<string | null> = rig.readAsync();
    await rig.azure.askedAsync(1);
    rig.token.answer("token", null);
    release(users());
    const changed: string | null = await reading;
    rig.token.answer("token", new FakeToken().token);
    const again: string | null = await rig.readAsync();

    assert.deepEqual([changed, again?.startsWith("data:image/png;base64,"), rig.azure.requests.length], [null, true, 3]);
  });

  it("keeps the last 500 emails' answers, forgetting the one read longest ago", async () => {
    const rig = new Rig();
    for (let i = 0; i <= 501; i++)
      rig.azure.answer(users());

    for (let i = 0; i <= 500; i++)
      await rig.readAsync(query(`author${i}@fabrikam.com`));
    await rig.readAsync(query("author500@fabrikam.com"));
    await rig.readAsync(query("author0@fabrikam.com"));

    assert.deepEqual([rig.azure.requests.length, rig.azure.requests.at(-1)?.init.body], [502, JSON.stringify({ query: "author0@fabrikam.com", subjectKind: ["User"] })]);
  });

  it("fails a user query Graph forbids as a refusal, keeping the sign-in", async () => {
    const rig = new Rig();
    rig.azure.answer(FakeAzure.json({ message: "Access denied." }, 403));

    const failure: unknown = await rig.readAsync().then(() => null, (t: unknown) => t);

    assert.deepEqual([failure instanceof MethodFailureException ? [failure.failure.code, failure.failure.message] : failure, rig.token.refused, rig.azure.urls()],
      [[FailureCode.Unavailable, "Azure DevOps refused the request (403)."], [], [queryUrl]]);
  });
});
