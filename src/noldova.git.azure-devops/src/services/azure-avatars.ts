import "@noldova/context.core";
import type { JsonReader } from "@noldova/context.json";
import type { IModuleLog } from "@noldova/desktop.runtime";
import type { AuthorQuery, PersonQuery } from "@noldova/git.hosting.protocol";

import type { IAzureToken } from "../interfaces/i-azure-token.ts";
import type { AzureCredential } from "../models/azure-credential.ts";
import { Resources } from "../resources.ts";
import { AzureApi } from "./azure-api.ts";

export class AzureAvatars {
  private readonly api: AzureApi;
  private readonly signIn: IAzureToken;
  private readonly log: IModuleLog;
  private readonly kept: Map<string, string | null> = new Map();

  public constructor(api: AzureApi, signIn: IAzureToken, log: IModuleLog) {
    this.api = api;
    this.signIn = signIn;
    this.log = log;
  }

  public readAuthorAvatarAsync(query: AuthorQuery, signal: AbortSignal): Promise<string | null> {
    return this.readByEmailAsync(query.host, query.path, query.email, signal);
  }

  public async readPersonAvatarAsync(query: PersonQuery, signal: AbortSignal): Promise<string | null> {
    return Resources.emailPattern.test(query.login.trim()) ? this.readByEmailAsync(query.host, query.path, query.login, signal) : null;
  }

  private async readByEmailAsync(host: string, organization: string, address: string, signal: AbortSignal): Promise<string | null> {
    const signedIn: string | null = this.signIn.organization;
    const token: AzureCredential | null = this.signIn.token;
    if (host !== Resources.host || Object.isNull(signedIn) || Object.isNull(token) || !Resources.isSameOrganization(signedIn, organization))
      return null;
    const email: string = address.trim().toLowerCase();
    const key: string = Resources.formatAvatarKey(signedIn, email);
    const known: string | null | undefined = this.kept.get(key);
    if (!Object.isUndefined(known))
      return known;
    let avatar: string | null;
    await this.signIn.readyAsync();
    try {
      avatar = await this.readAsync(signedIn, email, token, signal);
    }
    catch (error) {
      if (AzureApi.isUnauthorized(error))
        await this.signIn.refusedAsync(token);
      throw error;
    }
    if (this.signIn.token !== token)
      return null;
    this.keep(key, avatar);
    return avatar;
  }

  private async readAsync(organization: string, email: string, token: AzureCredential, signal: AbortSignal): Promise<string | null> {
    const users: JsonReader | null = await this.api.postAsync(Resources.formatSubjectQueryUrl(organization), token,
      { [Resources.queryField]: email, [Resources.subjectKindField]: [Resources.userKind] }, signal);
    const descriptor: string | null = Object.isNull(users) ? null : AzureApi.read(() => users.readObjectArray(Resources.valueField)
      .find(t => t.readNullableString(Resources.mailAddressField)?.toLowerCase() === email)?.readString(Resources.descriptorField) ?? null);
    if (Object.isNull(descriptor))
      return null;
    const avatar: JsonReader | null = await this.api.getAsync(Resources.formatAvatarUrl(organization, descriptor), token, signal);
    if (Object.isNull(avatar) || AzureApi.read(() => avatar.readBoolean(Resources.isAutoGeneratedField)))
      return null;
    return this.imageOf(Buffer.from(AzureApi.read(() => avatar.readString(Resources.valueField)), Resources.base64Encoding));
  }

  private imageOf(bytes: Buffer): string | null {
    if (bytes.length === 0 || bytes.length > Resources.maximumAvatarBytes)
      return this.drop(bytes.length === 0 ? Resources.avatarEmpty : Resources.avatarTooLarge);
    for (const [type, marks] of Resources.imageSignatures) {
      if (marks.every((mark, at) => mark === Resources.anyByte || bytes[at] === mark))
        return Resources.formatDataUrl(type, bytes.toString(Resources.base64Encoding));
    }
    return this.drop(Resources.avatarNotImage);
  }

  private drop(reason: string): null {
    this.log.write(Resources.formatAvatarDropped(reason));
    return null;
  }

  private keep(key: string, avatar: string | null): void {
    this.kept.delete(key);
    this.kept.set(key, avatar);
    for (const oldest of this.kept.keys()) {
      if (this.kept.size <= Resources.avatarCacheSize)
        break;
      this.kept.delete(oldest);
    }
  }
}
